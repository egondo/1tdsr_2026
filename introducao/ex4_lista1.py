num_a = int(input("Valor do 1 numero: "))
num_b = int(input("Valor do 2 numero: "))

print("A soma vale", num_a + num_b)

produto = num_a * num_b
print("O produto vale", produto)

quoci = num_a // num_b
print("O resultado da divisao vale", quoci)

resto = num_a % num_b
print("O resto da divisao vale", resto)

